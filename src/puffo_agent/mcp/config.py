def puffo_core_mcp_env(
    *,
    slug: str,
    device_id: str,
    server_url: str,
    space_id: str = "",
    keystore_dir: str,
    workspace: str,
    agent_id: str = "",
    data_service_url: str = "http://127.0.0.1:63386",
    rpc_url: str = "http://127.0.0.1:63385",
    runtime_kind: str = "",
    harness: str = "",
    memory_dir: str = "",
    transport: str = "",
) -> dict[str, str]:
    """Env dict for the puffo-core MCP subprocess. The MCP never
    touches ``messages.db`` or ``~/.claude.json`` directly — the
    daemon owns both. cli-docker rewrites the loopback URLs to
    ``host.docker.internal``. ``memory_dir`` (optional) pins the
    memory root for the M3 memory tools; when empty the server falls
    back to the workspace-sibling ``memory/`` dir."""
    from ..portal.local_service_auth import (
        LOCAL_SERVICE_TOKEN_ENV,
        issue_local_service_token,
    )

    effective_agent_id = agent_id or slug
    env: dict[str, str] = {
        "PUFFO_CORE_SLUG": slug,
        "PUFFO_CORE_DEVICE_ID": device_id,
        "PUFFO_CORE_SERVER_URL": server_url,
        "PUFFO_CORE_KEYSTORE_DIR": keystore_dir,
        "PUFFO_WORKSPACE": workspace,
        "PUFFO_DATA_SERVICE_URL": data_service_url,
        "PUFFO_RPC_URL": rpc_url,
        LOCAL_SERVICE_TOKEN_ENV: issue_local_service_token(effective_agent_id),
        **_python_user_base_env(runtime_kind),
    }
    # The MCP starts with the agent workspace as cwd. A relative PYTHONPATH
    # would therefore resolve against the wrong directory and can silently
    # load a different editable checkout than the daemon.
    pythonpath = _mcp_pythonpath(runtime_kind)
    if pythonpath:
        env["PYTHONPATH"] = pythonpath
    if agent_id:
        env["PUFFO_AGENT_ID"] = agent_id
    if space_id:
        env["PUFFO_CORE_SPACE_ID"] = space_id
    if runtime_kind:
        env["PUFFO_RUNTIME_KIND"] = runtime_kind
    if harness:
        env["PUFFO_HARNESS"] = harness
    if memory_dir:
        env["PUFFO_MEMORY_DIR"] = memory_dir
    # T23 phase-2: the cli-local / cli-docker worker call sites now
    # forward ``pc.transport``. Only ``bridge`` flips the subprocess to
    # keyless (``puffo_core_server.build_server`` does
    # ``keyless=(transport == "bridge")``), so emit the env var only for
    # bridge. Native agents (the default transport, a truthy string)
    # therefore stay byte-for-byte identical — no PUFFO_CORE_TRANSPORT
    # key, subprocess keeps ``keyless=False`` and its signed keystore
    # path.
    if transport == "bridge":
        env["PUFFO_CORE_TRANSPORT"] = transport
    # Test-only egress shim: forward PUFFO_LOCAL_SANDBOX_TOKEN into the
    # subprocess so its keyless http client can simulate the E2B egress
    # token injection against a local server. Guarded on presence in the
    # daemon environment — production leaves it unset, so nothing is
    # written to any config file.
    import os as _os
    local_sandbox_token = _os.environ.get("PUFFO_LOCAL_SANDBOX_TOKEN")
    if local_sandbox_token:
        env["PUFFO_LOCAL_SANDBOX_TOKEN"] = local_sandbox_token
    # codex only forwards [mcp_servers.puffo.env] to the subprocess,
    # so CODEX_HOME must be pinned explicitly or list_mcp_servers
    # would read the operator's host config instead of the agent's.
    if harness == "codex" and workspace:
        from pathlib import Path as _Path
        env["CODEX_HOME"] = str(_Path(workspace).parent / ".codex")
    return env
